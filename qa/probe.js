const fs = require('fs'); const OUT = process.env.OUT || 'probe-out'; fs.mkdirSync(OUT, { recursive: true });
const { chromium, devices } = require('playwright');
const S = 'https://abtkar2011-bot.github.io/Qarin/';
const lines = []; const L = (...a) => { const s = a.join(' '); console.log(s); lines.push(s); fs.writeFileSync(OUT + '/report.txt', lines.join('\n')); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['Desktop Chrome'], locale: 'ar-OM' });
  await ctx.addInitScript(() => { localStorage.setItem('qarin.instHide', String(Date.now())); });
  const p = await ctx.newPage(); p.setDefaultTimeout(9000);
  const cdp = await ctx.newCDPSession(p); await cdp.send('Network.enable');
  let step = '';
  cdp.on('Network.requestWillBeSent', e => { if (e.request.url.includes('%7B') || e.request.url.includes('${')) L('TEMPLATE', step, e.request.url.slice(-40), 'doc', (e.documentURL || '').slice(-40), 'init', JSON.stringify(e.initiator).slice(0, 400)); });
  const go = async (n, fn) => { step = n; try { await fn(); L('step', n, 'ok'); } catch (e) { L('step', n, 'ERR', e.message.slice(0, 100)); } };
  await go('home', async () => { await p.goto(S + '?t=' + Date.now()); await p.waitForTimeout(4000); });
  await go('search', async () => { await p.fill('#q', 'سماعات لاسلكية'); await p.press('#q', 'Enter'); await p.waitForTimeout(9000); });
  await go('perfume', async () => { await p.goto(S + '#perfume'); await p.waitForTimeout(3000); await p.fill('#pfQ', 'dior sauvage'); await p.press('#pfQ', 'Enter'); await p.waitForTimeout(7000); });
  await go('coffee', async () => { await p.goto(S + '#coffee'); await p.waitForTimeout(3000); await p.fill('#cfQ', 'قهوة اثيوبية'); await p.press('#cfQ', 'Enter'); await p.waitForTimeout(7000); });
  await go('coupons', async () => { await p.goto(S + 'coupons.html'); await p.waitForTimeout(2500); });
  await go('admin', async () => { await p.goto(S + 'admin/'); await p.waitForTimeout(2500); });
  await go('stats', async () => { await p.goto(S + 'stats.html'); await p.waitForTimeout(2500); });
  L('done'); await b.close();
})();
